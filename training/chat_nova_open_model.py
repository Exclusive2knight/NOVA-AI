"""Try a Qwen3+NOVA LoRA adapter in a private local/Colab GPU session.

This loads an openly licensed pretrained base model and your locally trained
LoRA adapter. It does not alter the publicly deployed NOVA app.
"""
import argparse


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--adapter", default="nova-data/nova-qwen-lora/adapter")
    parser.add_argument("--prompt", default="How are we doing with NOVA?")
    parser.add_argument("--max-new-tokens", type=int, default=140)
    args = parser.parse_args()
    if not 1 <= args.max_new_tokens <= 600:
        raise ValueError("max-new-tokens must be 1..600")
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from peft import PeftModel
    if not torch.cuda.is_available():
        raise RuntimeError("A CUDA GPU is required for this starter demo")
    model_id = "Qwen/Qwen3-0.6B"
    dtype = torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16
    tokenizer = AutoTokenizer.from_pretrained(model_id, trust_remote_code=False)
    base = AutoModelForCausalLM.from_pretrained(
        model_id, trust_remote_code=False, dtype=dtype, attn_implementation="sdpa"
    ).to("cuda")
    model = PeftModel.from_pretrained(base, args.adapter, is_trainable=False)
    model.eval()
    messages = [
        {"role": "system", "content": (
            "You are NOVA. Answer questions directly, distinguish verified work from plans, "
            "protect privacy and admit uncertainty when necessary."
        )},
        {"role": "user", "content": args.prompt[:2000]},
    ]
    encoded = tokenizer.apply_chat_template(
        messages, tokenize=True, add_generation_prompt=True,
        enable_thinking=False, return_tensors="pt"
    ).to("cuda")
    with torch.inference_mode():
        output = model.generate(
            encoded, max_new_tokens=args.max_new_tokens,
            do_sample=False, pad_token_id=tokenizer.eos_token_id,
        )
    reply = tokenizer.decode(output[0, encoded.shape[1]:], skip_special_tokens=True)
    print("\nNOVA fine-tuned adapter response:\n" + reply.strip())
    print("\nThis result is experimental. It was generated by the open model plus your LoRA adapter.")


if __name__ == "__main__":
    main()
